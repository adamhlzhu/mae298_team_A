'''
This script reads the CSVs generated by BWB_geometry_generator and plots carpet plots.
Most of it is hard-coded, so there's no generalization here.
'''
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import ast


df_lr = pd.read_csv("temp/BWB_coefficients_length_ratio.CSV", index_col=0, header=None).T
df_lr.columns = ['length', 'ratio', 'CLs', 'CDs']
df_ss = pd.read_csv("temp/BWB_coefficients_span_sweep.CSV", index_col=0, header=None).T
df_ss.columns = ['span', 'sweep', 'CLs', 'CDs']

# --- Data Processing ---
# This function calculates the aerodynamic metrics for a single row of data.
def calculate_aero_metrics(row):
    # Safely convert string representations of lists into actual lists
    CLs = ast.literal_eval(row['CLs'])
    CDs = ast.literal_eval(row['CDs'])
    
    alphas = [0, 2.5, 5, 7.5, 10]
    alpha_evals = np.linspace(0, 10, 1000)
    
    CL_interpolated = np.interp(alpha_evals, alphas, CLs)
    CD_interpolated = np.interp(alpha_evals, alphas, CDs)

    # Calculate L/D, handling potential division by zero
    with np.errstate(divide='ignore', invalid='ignore'):
        L_D_interpolated = np.nan_to_num(CL_interpolated / CD_interpolated)
    
    max_L_D_index = np.argmax(L_D_interpolated)
    max_L_D = L_D_interpolated[max_L_D_index]
    # CL_at_max = CL_interpolated[max_L_D_index]

    alpha_0 = alpha_evals[np.argmin(np.abs(CL_interpolated))]
    
    return max_L_D, alpha_0


# Apply the function to each row and create new columns for the results
df_lr[['max_L_D', 'alpha_0']] = df_lr.apply(calculate_aero_metrics, axis=1, result_type='expand')
df_ss[['max_L_D', 'alpha_0']] = df_ss.apply(calculate_aero_metrics, axis=1, result_type='expand')


# --- Plotting ---
fig, ax = plt.subplots(figsize=(10, 8))

# Plot lines of constant length
for length_val, group in df_lr.groupby('length'):
    ax.plot(group['max_L_D'], group['alpha_0'], 'o-', label=f'Fuselage Length = {length_val}')

# Plot lines of constant ratio
for ratio_val, group in df_lr.groupby('ratio'):
    ax.plot(group['max_L_D'], group['alpha_0'], 's--', label=f'Fuselage Height-To-Width Ratio= {float(ratio_val):.2f}')

ax.set_xlabel("Maximum Lift-to-Drag Ratio (L/D_max)")
ax.set_ylabel("Alpha at CL=0")
ax.set_title("Fuselage Parameters vs. L/D and Alpha at CL=0")
ax.legend(title="Parameters")
ax.grid(True)


# --- Plotting ---
fig, ax = plt.subplots(figsize=(10, 8))

# Plot lines of constant length
for span_val, group in df_ss.groupby('span'):
    ax.plot(group['max_L_D'], group['alpha_0'], 'o-', label=f'Wing Span = {span_val}')

# Plot lines of constant ratio
for sweep_val, group in df_ss.groupby('sweep'):
    ax.plot(group['max_L_D'], group['alpha_0'], 's--', label=f'Wing Sweep = {float(sweep_val):.2f}')

ax.set_xlabel("Maximum Lift-to-Drag Ratio (L/D_max)")
ax.set_ylabel("Alpha at CL=0")
ax.set_title("Wing Parameters vs. L/D and Alpha at CL=0")
ax.legend(title="Parameters")
ax.grid(True)


plt.show()
